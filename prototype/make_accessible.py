"""Prototype: turn lecture PDF slides into accessible HTML.

Pipeline per slide
  1. Pull the slide title from the PDF text layer (pdftotext).
  2. Take the AI step output from slides.json (overview, parts,
     relationships, formulas as LaTeX, table values).
  3. Convert LaTeX to MathML with pandoc so screen readers can speak it.
  4. Emit semantic HTML: headings for navigation, a layered description
     (overview, parts, relationships), real <math> and real <table>s.

Usage: python3 make_accessible.py cs231n_lecture2.pdf slides.json out.html
"""
import html
import json
import re
import subprocess
import sys


def slide_title(pdf, page):
    text = subprocess.run(
        ["pdftotext", "-f", str(page), "-l", str(page), pdf, "-"],
        capture_output=True, text=True, check=True).stdout
    return next(line.strip() for line in text.splitlines() if line.strip())


def latex_to_mathml(latex):
    out = subprocess.run(
        ["pandoc", "-f", "markdown", "-t", "html", "--math-method=mathml"],
        input=f"$${latex}$$", capture_output=True, text=True, check=True).stdout
    return re.search(r"<math.*</math>", out, re.S).group(0)


def table_html(t):
    head = "".join(f'<th scope="col">Column {c + 1}</th>' for c in range(len(t["rows"][0])))
    body = "".join(
        f'<tr><th scope="row">Row {r + 1}</th>' + "".join(f"<td>{v}</td>" for v in row) + "</tr>"
        for r, row in enumerate(t["rows"]))
    return (f'<table><caption>{html.escape(t["caption"])}</caption>'
            f'<thead><tr><td></td>{head}</tr></thead><tbody>{body}</tbody></table>')


def slide_html(pdf, s):
    e = html.escape
    title = slide_title(pdf, s["page"])
    parts = "".join(f"<li>{e(p)}</li>" for p in s["parts"])
    maths = "".join(
        f'<p>{e(m["spoken_context"])}</p>{latex_to_mathml(m["latex"])}' for m in s["math"])
    tables = "".join(table_html(t) for t in s["tables"])
    return f"""
<section aria-labelledby="s{s['page']}">
  <h2 id="s{s['page']}">Slide {s['page']}: {e(title)}</h2>
  <h3>Overview</h3><p>{e(s['overview'])}</p>
  <h3>Parts</h3><ul>{parts}</ul>
  <h3>How the parts relate</h3><p>{e(s['relationships'])}</p>
  {'<h3>Formulas</h3>' + maths if maths else ''}
  {'<h3>Tables</h3>' + tables if tables else ''}
</section>"""


def main(pdf, spec, out):
    slides = json.load(open(spec))["slides"]
    body = "".join(slide_html(pdf, s) for s in slides)
    page = f"""<title>Lecture 2 Accessible</title>
<style>
:root{{--bg:#ffffff;--fg:#1b1f23;--line:#c9ced3}}
@media (prefers-color-scheme:dark){{:root:not([data-theme="light"]){{--bg:#16191c;--fg:#e7eaed;--line:#3a4046;color-scheme:dark}}}}
:root[data-theme="dark"]{{--bg:#16191c;--fg:#e7eaed;--line:#3a4046;color-scheme:dark}}
body{{background:var(--bg);color:var(--fg);font:17px/1.6 system-ui,sans-serif;padding-inline:16px;padding-block:32px}}
main{{max-width:760px;margin:0 auto}}
section{{border-top:1px solid var(--line);padding-top:12px;margin-top:24px}}
.wrap{{overflow-x:auto}} table{{border-collapse:collapse;margin:10px 0}}
th,td{{border:1px solid var(--line);padding:4px 8px;text-align:right}}
caption{{text-align:left;font-weight:600;padding:4px 0}}
</style>
<main>
<h1>CS231n Lecture 2, accessible version (slides 22, 23 and 52)</h1>
<p>Generated by the prototype pipeline from the original untagged PDF.</p>
{body}
</main>"""
    open(out, "w").write(page)


if __name__ == "__main__":
    main(*sys.argv[1:4])
